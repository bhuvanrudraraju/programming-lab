/*Vehicle Service Management System:
A service centre maintains service records of 10 vehicles.
Each record contains Vehicle Number, Owner Name, Vehicle Type 
and Service Cost. Develop a C program using structures and arrays
to read and display service records, identify the vehicle with 
the highest service cost using a user-defined function, and 
calculate the total service revenue generated by the service centre using recursion.
*/
#include <stdio.h>

struct Vehicle {
    char number[20], name[50], type[50];
    double cost;
};

int highest(struct Vehicle v[], int n) {
    int max = 0;
    for (int i = 1; i < n; i++) {
        if (v[i].cost > v[max].cost)
            max = i;
    }
    return max;
}

double totalRevenue(struct Vehicle v[], int n) {
    if (n == 0)
        return 0;
    return v[n - 1].cost + totalRevenue(v, n - 1);
}

int main() {
    struct Vehicle v[10];
    int i, max;

    for (i = 0; i < 10; i++) {
        printf("\nVehicle %d\n", i + 1);
        printf("Vehicle number: ");
        scanf(" %19[^\n]", v[i].number);
        printf("Owner name: ");
        scanf(" %49[^\n]", v[i].name);
        printf("Vehicle type: ");
        scanf(" %49[^\n]", v[i].type);
        printf("Service cost: ");
        scanf("%lf", &v[i].cost);
    }

    printf("\nVehicle Number | Owner | Vehicle Type | Service Cost\n");
    for (i = 0; i < 10; i++)
        printf("%s | %s | %s | %.2f\n",
               v[i].number, v[i].name, v[i].type, v[i].cost);

    max = highest(v, 10);
    printf("\nHighest service cost: %s, %s, %.2f\n",
           v[max].number, v[max].name, v[max].cost);
    printf("Total service revenue: %.2f\n", totalRevenue(v, 10));

    return 0;
}
